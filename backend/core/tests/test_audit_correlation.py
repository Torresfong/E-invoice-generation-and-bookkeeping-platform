from core import audit, jobs
from core.audit import audit_trigger_sql
from core.models import AuditEntry, CompanyAccess, FirmAuditEntry, User
from core.rls import tenant_policy_sql

from .factories import PASSWORD


def sign_in(client, user):
    return client.post("/login/", {"email": user.email, "password": PASSWORD})


@pytest.fixture
def notes_table(db, settings):
    settings.ROOT_URLCONF = "core.tests.urls_probe"
    with connection.cursor() as cursor:
        cursor.execute(
            "CREATE TABLE probe_note (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, "
            "company_id bigint NOT NULL REFERENCES core_company(id), body text NOT NULL)"
        )
        for statement in [*tenant_policy_sql("probe_note", worker=True), *audit_trigger_sql("probe_note")]:
            cursor.execute(statement)


def test_a_company_entry_made_in_a_request_carries_that_requests_correlation_id(
    client, firms_world, notes_table, as_production_connection
):
    acme = firms_world["acme"]
    owner = User.objects.get(email="owner@acme.example")
    with as_production_connection():
        sign_in(client, owner)
        requests = [client.post("/notes/", {"company": acme.pk, "body": body}).json() for body in ("one", "two")]

    entries = AuditEntry.objects.filter(target_type="probe_note").order_by("id")
    assert [str(e.correlation_id) for e in entries] == [r["correlation_id"] for r in requests]
    assert requests[0]["correlation_id"] != requests[1]["correlation_id"]


def test_a_company_move_shows_one_id_on_the_company_entry_and_both_firm_entries(firms_world):
    call_command("move_company", firms_world["acme"].pk, "Beta Books")

    company_entries = AuditEntry.objects.filter(company=firms_world["acme"], action=AuditEntry.UPDATE, changed_fields=["firm"])
    firm_entries = FirmAuditEntry.objects.filter(target_type="company")
    ids = {e.correlation_id for e in [*company_entries, *firm_entries]}
    assert company_entries.count() == 1 and firm_entries.count() == 2 and len(ids) == 1 and None not in ids


def test_entries_made_by_a_job_carry_the_jobs_correlation_id(firms_world, notes_table):
    seen = []

    @jobs.register("probe.audited")
    def handler(**_):
        with connection.cursor() as cursor:
            cursor.execute(
                "INSERT INTO probe_note (company_id, body) VALUES "
                "(current_setting('app.company_id')::bigint, 'a'), (current_setting('app.company_id')::bigint, 'b')"
            )
        seen.append(audit.current_correlation_id())

    try:
        jobs.enqueue("probe.audited", company=firms_world["acme"])
        jobs.run_pending()
    finally:
        jobs.HANDLERS.pop("probe.audited")

    ids = {e.correlation_id for e in AuditEntry.objects.filter(target_type="probe_note")}
    assert len(ids) == 1 and ids == set(seen)


def test_a_sign_in_entry_carries_the_requests_correlation_id(client, firms_world, as_production_connection):
    owner = User.objects.get(email="owner@acme.example")
    with as_production_connection():
        sign_in(client, owner)

    assert AuditEntry.objects.get(action=AuditEntry.LOGIN, company=firms_world["acme"]).correlation_id is not None


def test_rows_written_before_the_column_existed_stay_null(firms_world):
    # A migration test would need a second database; the column default must not back-fill, so a row inserted
    # explicitly with NULL stays NULL and the model allows it.
    entry = AuditEntry.objects.create(company=firms_world["acme"], actor_email="x", action=AuditEntry.UPDATE, correlation_id=None)

    entry.refresh_from_db()
    assert entry.correlation_id is None


def test_one_sign_in_event_has_one_correlation_id_across_all_the_users_companies(firms_world, as_user):
    owner = User.objects.get(email="owner@acme.example")
    CompanyAccess.objects.create(user=owner, company=firms_world["gamma"], role=CompanyAccess.STAFF)

    with as_user(owner), connection.cursor() as cursor:
        cursor.execute("SELECT record_auth_event('login', NULL)")

    entries = AuditEntry.objects.filter(action=AuditEntry.LOGIN)
    assert entries.count() == 2 and len({e.correlation_id for e in entries}) == 1
