def test_the_job_table_is_in_no_screen_api_or_admin():
    # Best effort: it pins the usual ways to expose the table (admin, DRF, a route that names jobs), not every view.
    def routes(patterns, prefix=""):
        for pattern in patterns:
            text = prefix + str(pattern.pattern)
            if hasattr(pattern, "url_patterns"):
                yield from routes(pattern.url_patterns, text)
            else:
                yield f"{text} {pattern.name or ''} {getattr(pattern.callback, '__module__', '')}"

    assert "django.contrib.admin" not in settings.INSTALLED_APPS
    assert not any(app.startswith("rest_framework") for app in settings.INSTALLED_APPS)
    assert not [route for route in routes(get_resolver("config.urls").url_patterns) if "job" in route.lower()]


